from decimal import Decimal

from django.test import TestCase
from django.urls import reverse

from accounts.models import User
from store.models import BaristaNote, BrewGuide, BrewStep, Category, Product


class StoreViewTests(TestCase):
    @classmethod
    def setUpTestData(cls):
        cls.category = Category.objects.create(name="Coffee", icon="☕")
        cls.product = Product.objects.create(
            name="Test Latte",
            category=cls.category,
            kind=Product.Kind.DRINK,
            price=Decimal("4.50"),
        )

    def test_home_page(self):
        response = self.client.get(reverse("store:home"))
        self.assertEqual(response.status_code, 200)
        self.assertContains(response, "Coffee")

    def test_menu_page(self):
        response = self.client.get(reverse("store:menu"))
        self.assertEqual(response.status_code, 200)
        self.assertContains(response, "Test Latte")

    def test_product_detail(self):
        response = self.client.get(self.product.get_absolute_url())
        self.assertEqual(response.status_code, 200)
        self.assertContains(response, "Test Latte")

    def test_newsletter_subscribe(self):
        response = self.client.post(reverse("store:subscribe"), {"email": "a@b.com"})
        self.assertEqual(response.status_code, 302)

    def test_slug_autogenerated(self):
        self.assertEqual(self.product.slug, "test-latte")


class BrewGuideTests(TestCase):
    @classmethod
    def setUpTestData(cls):
        cls.category = Category.objects.create(name="Beans", icon="🫘")
        cls.product = Product.objects.create(
            name="House Blend",
            category=cls.category,
            kind=Product.Kind.BEANS,
            price=Decimal("15.00"),
        )
        cls.guide = BrewGuide.objects.create(
            product=cls.product,
            title="Everyday pour-over",
            method=BrewGuide.Method.POUR_OVER,
            total_time_minutes=5,
            ratio="1:15",
        )
        BrewStep.objects.create(
            guide=cls.guide, order=0, title="Bloom", instruction="Pour 60ml and wait."
        )
        BrewStep.objects.create(
            guide=cls.guide, order=1, title="Pour", instruction="Top up to 300ml."
        )
        BaristaNote.objects.create(
            product=cls.product, author="Marta", body="Let the beans rest first."
        )

    def test_guide_step_count(self):
        self.assertEqual(self.guide.step_count, 2)

    def test_product_page_shows_guide_and_notes(self):
        response = self.client.get(self.product.get_absolute_url())
        self.assertEqual(response.status_code, 200)
        self.assertContains(response, "Everyday pour-over")
        self.assertContains(response, "Bloom")
        self.assertContains(response, "1:15")
        self.assertContains(response, "Let the beans rest first.")

    def test_unpublished_guide_hidden(self):
        self.guide.is_published = False
        self.guide.save(update_fields=["is_published"])
        response = self.client.get(self.product.get_absolute_url())
        self.assertNotContains(response, "Everyday pour-over")
