class StoreViewTests(TestCase):
    @classmethod
    def setUpTestData(cls):
        cls.category = Category.objects.create(name="Coffee", icon="☕")
        cls.product = Product.objects.create(
            name="Test Latte",
            category=cls.category,
            kind=Product.Kind.DRINK,
            price=Decimal("4.50"),
        )

    def test_home_page(self):
        response = self.client.get(reverse("store:home"))
        self.assertEqual(response.status_code, 200)
        self.assertContains(response, "Coffee")

    @override_settings(HERO_VIDEO_URL="/static/video/hero-coffee.mp4")
    def test_home_page_renders_hero_video_and_credit(self):
        response = self.client.get(reverse("store:home"))
        self.assertContains(response, 'class="hero-video"')
        self.assertContains(response, "/static/video/hero-coffee.mp4")
        self.assertContains(response, "Adobe Stock")

    @override_settings(HERO_VIDEO_URL="")
    def test_home_page_falls_back_without_video(self):
        response = self.client.get(reverse("store:home"))
        self.assertContains(response, 'class="hero-video-fallback"')
        self.assertNotContains(response, 'class="hero-video"')

    def test_menu_page(self):
        response = self.client.get(reverse("store:menu"))
        self.assertEqual(response.status_code, 200)
        self.assertContains(response, "Test Latte")

    def test_product_detail(self):
        response = self.client.get(self.product.get_absolute_url())
        self.assertEqual(response.status_code, 200)
        self.assertContains(response, "Test Latte")

    def test_newsletter_subscribe(self):
        response = self.client.post(reverse("store:subscribe"), {"email": "a@b.com"})
        self.assertEqual(response.status_code, 302)

    def test_slug_autogenerated(self):
        self.assertEqual(self.product.slug, "test-latte")

    def test_menu_search_by_query(self):
        response = self.client.get(reverse("store:menu"), {"q": "latte"})
        self.assertEqual(response.status_code, 200)
        self.assertContains(response, "Test Latte")

    def test_menu_sorts_by_approved_rating(self):
        best = Product.objects.create(
            name="Best Latte",
            category=self.category,
            kind=Product.Kind.DRINK,
            price=Decimal("5.00"),
        )
        reviewer = User.objects.create_user(
            email="reviewer@example.com", password="reviewpass123"
        )
        Review.objects.create(
            product=best, user=reviewer, rating=5, body="Excellent."
        )
        response = self.client.get(reverse("store:menu"), {"sort": "rating"})
        self.assertEqual(response.status_code, 200)
        products = list(response.context["products"])
        self.assertEqual(products[0].pk, best.pk)

    def test_navbar_renders_enhanced_markup(self):
        response = self.client.get(reverse("store:home"))
        self.assertContains(response, 'class="topbar"')
        self.assertContains(response, 'id="nav-search"')
        self.assertContains(response, "nav-toggle")
        self.assertContains(response, reverse("orders:cart"))


class BrewGuideTests(TestCase):
    @classmethod
    def setUpTestData(cls):
        cls.category = Category.objects.create(name="Beans", icon="🫘")
        cls.product = Product.objects.create(
            name="House Blend",
            category=cls.category,
            kind=Product.Kind.BEANS,
            price=Decimal("15.00"),
        )
        cls.guide = BrewGuide.objects.create(
            product=cls.product,
            title="Everyday pour-over",
            method=BrewGuide.Method.POUR_OVER,
            total_time_minutes=5,
            ratio="1:15",
        )
        BrewStep.objects.create(
            guide=cls.guide, order=0, title="Bloom", instruction="Pour 60ml and wait."
        )
        BrewStep.objects.create(
            guide=cls.guide, order=1, title="Pour", instruction="Top up to 300ml."
        )
        BaristaNote.objects.create(
            product=cls.product, author="Marta", body="Let the beans rest first."
        )

    def test_guide_step_count(self):
        self.assertEqual(self.guide.step_count, 2)

    def test_product_page_shows_guide_and_notes(self):
        response = self.client.get(self.product.get_absolute_url())
        self.assertEqual(response.status_code, 200)
        self.assertContains(response, "Everyday pour-over")
        self.assertContains(response, "Bloom")
        self.assertContains(response, "1:15")
        self.assertContains(response, "Let the beans rest first.")

    def test_unpublished_guide_hidden(self):
        self.guide.is_published = False
        self.guide.save(update_fields=["is_published"])
        response = self.client.get(self.product.get_absolute_url())
        self.assertNotContains(response, "Everyday pour-over")


class SubscriptionPlanTests(TestCase):
    def test_feature_sections_group_perks(self):
        plan = SubscriptionPlan.objects.create(
            name="Bean Curious",
            price=Decimal("9000.00"),
            interval=SubscriptionPlan.Interval.MONTHLY,
            bags_per_delivery=1,
            perks="1 bag (250g) monthly\nFree delivery\nPause anytime",
        )
        sections = {item["title"]: item["perks"] for item in plan.feature_sections}
        self.assertEqual(sections["In your box"], ["1 bag (250g) monthly"])
        self.assertEqual(sections["Delivery & service"], ["Free delivery"])
        self.assertEqual(sections["Member benefits"], ["Pause anytime"])

    def test_subscriptions_page_shows_sectioned_plans(self):
        SubscriptionPlan.objects.create(
            name="True Brew",
            tagline="Our most popular subscription",
            price=Decimal("24000.00"),
            interval=SubscriptionPlan.Interval.BIWEEKLY,
            bags_per_delivery=2,
            perks="2 bags (500g) every 2 weeks\nFree priority delivery\nChoose your roast",
            is_popular=True,
        )
        response = self.client.get(reverse("store:subscriptions"))
        self.assertEqual(response.status_code, 200)
        self.assertContains(response, "Plan 01")
        self.assertContains(response, "True Brew")
        self.assertContains(response, "In your box")
        self.assertContains(response, "Free priority delivery")


class LegalPageTests(TestCase):
    def test_legal_pages_render(self):
        for slug in ("privacy", "terms", "refunds", "accessibility"):
            response = self.client.get(reverse("store:legal", args=[slug]))
            self.assertEqual(response.status_code, 200)
            self.assertContains(response, "The small print")

    def test_unknown_legal_page_is_404(self):
        self.assertEqual(
            self.client.get(reverse("store:legal", args=["nope"])).status_code, 404
        )
